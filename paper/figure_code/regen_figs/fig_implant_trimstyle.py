#!/usr/bin/env python3
"""ESI figures: implant routes, TRIM-style views (full width, print size).
Draws the four-panel views of nano_sigec/implant/trim_style/make_trim_style.py
for the three recipes the ESI implant paragraph uses (C and He into
Si0.8Ge0.2, Kr into Si). Reads the SRIM outputs in nano_sigec/implant/srim_raw/
and the RustBCA range and track outputs regenerated by
nano_sigec/implant/trim_style/run_rustbca_tracks.sh (about 40 s on 4 threads;
default directory ~/mat_theory_trimstyle, override with TRIMSTYLE_DIR)."""
import os
import sys
from pathlib import Path

import paper_fig_style as S

S.apply_style()
sys.path.insert(0, str(S.PROJECT / "nano_sigec" / "implant" / "trim_style"))
import make_trim_style as T  # noqa: E402

T.RB = Path(os.environ.get("TRIMSTYLE_DIR", Path.home() / "mat_theory_trimstyle"))
if not (T.RB / "traj_C_Si0.8Ge0.2_40keV_trajectories.output").exists():
    sys.exit(f"RustBCA tracks not found in {T.RB}: run nano_sigec/implant/trim_style/"
             "run_rustbca_tracks.sh /path/to/RustBCA <dir> and set TRIMSTYLE_DIR=<dir>")
T.plt.rcParams.update({"font.size": 8, "axes.titlesize": 8, "axes.labelsize": 8,
                       "legend.fontsize": 7, "xtick.labelsize": 7, "ytick.labelsize": 7})
for rec, name in [("C_Si0.8Ge0.2_40keV", "fig_implant_C"),
                  ("He_Si0.8Ge0.2_40keV", "fig_implant_He"),
                  ("Kr_Si_500keV", "fig_implant_Kr")]:
    print(T.figure_recipe(rec, S.FIGDIR / name, figsize=(S.FULL, 5.0)))
